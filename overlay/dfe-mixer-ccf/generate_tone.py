"""Generate the registered 16-lane DAC sine ROM (10 GS/s, 256 samples)."""
from math import pi, sin
from pathlib import Path


def code(mode, index):
    harmonics = ((2,), (1,), (3,), (1, 3))[mode]
    return round(8192 * sum(sin(2*pi*h*index/256) for h in harmonics) / len(harmonics))


rows = []
for mode in range(4):
    for phase in range(16):
        word = sum((code(mode, 16*phase+i) & 0xffff) << (16*i) for i in range(16))
        rows.append(f"                6'd{16*mode+phase}: samples <= 256'h{word:064x};")

Path(__file__).with_name("dac_tone.v").write_text("""// SPDX-License-Identifier: BSD-3-Clause
// Generated by generate_tone.py. Select the waveform with playback disabled.
module dac_tone(input wire dac_clk, dac_resetn, ready, input wire [4:0] control,
                output reg [255:0] samples = 0, output wire [1:0] status);
    (* ASYNC_REG="TRUE" *) reg [2:0] ctrl_meta = 0, ctrl_sync = 0;
    reg [3:0] phase = 0;
    reg [15:0] stalled = 0;
    reg fault = 0;
    assign status = {fault, ctrl_sync[0]};
    always @(posedge dac_clk) begin
        ctrl_meta <= {control[4:3], control[0]};
        ctrl_sync <= ctrl_meta;
        if (!dac_resetn || !ctrl_sync[0]) begin
            phase <= 0;
            samples <= 0;
            stalled <= 0;
            if (!dac_resetn) fault <= 0;
        end else if (ready) begin
            stalled <= 0;
            phase <= phase + 1'b1;
            case ({ctrl_sync[2:1],phase})
""" + "\n".join(rows) + """
            endcase
        end else if (&stalled) fault <= 1;
        else stalled <= stalled + 1'b1;
    end
endmodule
""")
